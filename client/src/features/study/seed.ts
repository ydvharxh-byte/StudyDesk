export function createSeedChapters(): Chapter[] {
  return Object.entries(syllabus).flatMap(([subjectId, chapters]) =>
    chapters.map((chapter, index) => ({
      id: `seed-${subjectId}-${index + 1}`,
      subjectId: subjectId as SubjectId,
      name: chapter.name,
      section: chapter.section,
      syllabusNote: chapter.note,
      priorityRank: index + 1,
      priorityLevel: "Medium" as const,
      status: "not-started" as const,
      targetDate: "",
      notes: "",
      importantTopics: "",
      lastStudied: "",
      checklist: emptyChecklist(),
    })),
  );
}

export function createInitialData(): StudyData {
  return { chapters: createSeedChapters(), tasks: [], dailyChecklist: [], studyPlans: [], schoolwork: [], tuition: [], resources: [], topics: [] };
}
